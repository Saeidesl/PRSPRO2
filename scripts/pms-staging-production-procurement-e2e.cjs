const { chromium } = require('playwright');
const fs = require('node:fs');
const path = require('node:path');
const baseURL = (process.env.PMS_BASE_URL || 'https://saeidesl.github.io/PRSPRO2/').replace(/\/?$/, '/');
const username = process.env.PMS_TEST_USERNAME || '';
const password = process.env.PMS_TEST_PASSWORD || '';
const report = { suite: 'PMS staging production-to-procurement E2E', startedAt: new Date().toISOString(), environment: 'staging', steps: [], created: {}, status: 'running' };
const step = (name, data) => report.steps.push({ name, at: new Date().toISOString(), ...data });
const idOf = x => x && (x.ID || x.Id || x.id || x.ProjectID || x.EventTypeID || x.PurchaseOrderID);
const unwrap = x => x && x.data !== undefined ? x.data : x;
const arr = (x, keys) => { x = unwrap(x); if (Array.isArray(x)) return x; for (const k of keys) if (x && Array.isArray(x[k])) return x[k]; return []; };
(async () => {
  fs.mkdirSync('test-results', {recursive:true});
  let browser;
  try {
    if (!username || !password) throw new Error('Missing PMS_TEST_USERNAME/PMS_TEST_PASSWORD repository secrets; no records were written.');
    browser = await chromium.launch({headless:true});
    const page = await browser.newPage({viewport:{width:1365,height:900}});
    page.setDefaultTimeout(15000);
    await page.goto(baseURL + '#login', {waitUntil:'domcontentloaded'});
    await page.locator('#login-form').waitFor({state:'visible',timeout:20000});
    await page.locator('#login-username').fill(username);
    await page.locator('#login-password').fill(password);
    await page.locator('#login-button').click();
    await page.waitForFunction(() => !location.hash.includes('login'), null, {timeout:20000});
    const api = async (method, route, body) => page.evaluate(async ({method,route,body}) => {
      const api = window.PMS && window.PMS.Api;
      if (!api) throw new Error('PMS API client is unavailable after login');
      const response = method === 'GET' ? await api.get(route) : await api[method.toLowerCase()](route, body);
      return api.extractData(response);
    }, {method,route,body});
    const lookups = await api('GET','/project-form/lookups');
    const workflows = arr(lookups,['workflows','Workflows']);
    const departments = arr(lookups,['departments','Departments']);
    const statuses = arr(lookups,['statuses','projectStatuses','ProjectStatuses']);
    if (!workflows.length || !departments.length || !statuses.length) throw new Error('Project form lookups lack a workflow, department or project status; stopped before creating records.');
    const workflow = workflows.find(x => String(x.Status || 'ACTIVE').toUpperCase() === 'ACTIVE') || workflows[0];
    const department = departments.find(x => String(x.Status || 'ACTIVE').toUpperCase() === 'ACTIVE') || departments[0];
    const status = statuses.find(x => String(x.Status || 'ACTIVE').toUpperCase() === 'ACTIVE') || statuses[0];
    const stamp = new Date().toISOString().replace(/[-:.TZ]/g,'').slice(0,14);
    const code = 'QA_E2E_' + stamp;
    const projectResponse = await api('POST','/projects',{ProjectCode:code,Title:'QA E2E تولید تا تأمین '+stamp,Quantity:10,WorkflowID:idOf(workflow),Description:'TEST DATA — automated staging E2E; '+stamp,ColorSizeJSON:JSON.stringify({colors:[],sizes:[]}),AvailableDepartmentIDs:[idOf(department)],AllowedUserIDs:[],NotifyEnabled:false,Status:status.Code || status.StatusCode || status.Name || status.ID});
    const project = unwrap(projectResponse);
    const projectId = idOf(project && (project.project || project.Project || project));
    if (!projectId) throw new Error('Project create returned no project ID: '+JSON.stringify(projectResponse).slice(0,700));
    report.created.projectId = projectId; report.created.projectCode = code;
    step('create-project',{ok:true,projectId,projectCode:code,workflowId:idOf(workflow),departmentId:idOf(department)});
    await api('POST','/projects/'+encodeURIComponent(projectId)+'/material-specifications',{ItemName:'QA E2E fabric '+stamp,Unit:'meter',ConsumptionPerUnit:1.5,WastagePercent:0,Notes:'TEST DATA; auto-generated by E2E'});
    step('create-material-specification',{ok:true,consumptionPerUnit:1.5});
    const eventTypeResponse = await api('POST','/event-types',{Name:'QA E2E برش '+stamp,Code:'QA_CUT_'+stamp,ConnectionType:'PROJECT',Category:'PROCESS',DepartmentID:idOf(department),AllowedDepartmentIDs:[idOf(department)],AvailableDepartmentIDs:[idOf(department)],MovesProjectToStep:false,IsWorkCompletion:true,Status:'ACTIVE',Description:'TEST DATA; auto-generated E2E'});
    const eventType = unwrap(eventTypeResponse);
    const eventTypeId = idOf(eventType && (eventType.eventType || eventType.EventType || eventType));
    if (!eventTypeId) throw new Error('Event type create returned no ID: '+JSON.stringify(eventTypeResponse).slice(0,700));
    report.created.eventTypeId = eventTypeId;
    const fieldResponse = await api('POST','/event-types/'+encodeURIComponent(eventTypeId)+'/fields',{Name:'تعداد قطعی آزمایشی',Code:'ConfirmedQuantity',FieldType:'number',IsRequired:true,FieldOrder:1,Status:'ACTIVE'});
    const field = unwrap(fieldResponse); const fieldId = idOf(field && (field.field || field.Field || field));
    report.created.eventFieldId = fieldId || null;
    await api('POST','/event-types/'+encodeURIComponent(eventTypeId)+'/procurement',{Action:'RECALCULATE_CONFIRMED_NEEDS',FieldMap:{ConfirmedQuantity:'ConfirmedQuantity'}});
    step('configure-cut-event-type',{ok:true,eventTypeId,fieldId:fieldId||null});
    const eventResponse = await api('POST','/events',{ProjectID:projectId,EventTypeID:eventTypeId,EventTypeVersion:1,OccurredAt:new Date().toISOString(),Description:'QA E2E: ثبت تعداد قطعی ۱۰ عدد',DynamicData:{ConfirmedQuantity:10},VariantDetails:[],IdempotencyKey:'QA_E2E_EVENT_'+stamp});
    const event = unwrap(eventResponse); const eventObj = event.event || event.Event || event;
    const eventId = idOf(eventObj);
    if (!eventId) throw new Error('Event create returned no event ID: '+JSON.stringify(eventResponse).slice(0,900));
    report.created.eventId = eventId;
    step('register-cut-event',{ok:true,eventId,procurementIntegration:event.procurementIntegration||null});
    const needsResponse = await api('GET','/procurement/needs');
    const needs = arr(needsResponse,['needs','Needs','items','Items']);
    const need = needs.find(n => String(n.ProjectID)===String(projectId) && String(n.Status||'ACTIVE').toUpperCase()!=='DELETED');
    if (!need) throw new Error('No material need appeared for the test project after registering the cut quantity.');
    const expected = Math.ceil(10*1.5*10000)/10000;
    const requested = Number(need.RequestedQuantity);
    if (Math.abs(requested-expected)>0.0001) throw new Error('Material need mismatch: expected '+expected+', received '+requested);
    report.created.materialNeedId=idOf(need);
    step('verify-material-need',{ok:true,needId:idOf(need),expectedQuantity:expected,actualQuantity:requested});
    const orderResponse = await api('POST','/procurement/orders',{ProjectID:projectId,SupplierName:'QA E2E supplier',Notes:'TEST DATA; auto-generated E2E',IdempotencyKey:'QA_E2E_ORDER_'+stamp,Items:[{ProjectID:projectId,MaterialNeedID:idOf(need),ItemName:need.ItemName||'QA E2E material',Unit:need.Unit||'meter',OrderedQuantity:requested}]});
    const orderResult=unwrap(orderResponse); const order=orderResult.Order||orderResult.order||orderResult;
    const orderId=idOf(order); const orderItems=arr(orderResult,['Items','items']);
    const orderItem=orderItems[0];
    const orderItemId=idOf(orderItem);
    if(!orderId||!orderItemId) throw new Error('Order create returned missing order/item ID: '+JSON.stringify(orderResult).slice(0,900));
    report.created.orderId=orderId; report.created.orderItemId=orderItemId;
    step('create-procurement-order',{ok:true,orderId,orderItemId,orderedQuantity:requested});
    const receiptResponse=await api('POST','/procurement/receipts/batch',{Receipts:[{PurchaseOrderItemID:orderItemId,ProjectID:projectId,QuantityReceived:Math.max(1,Math.floor(requested/2)),IdempotencyKey:'QA_E2E_RECEIPT_'+stamp,Notes:'QA E2E partial receipt'}]});
    step('record-partial-receipt',{ok:true,response:JSON.stringify(unwrap(receiptResponse)).slice(0,400)});
    const finalNeeds=arr(await api('GET','/procurement/needs'),['needs','Needs','items','Items']);
    const finalNeed=finalNeeds.find(n=>String(n.ProjectID)===String(projectId)&&String(idOf(n))===String(idOf(need)));
    const finalOrders=arr(await api('GET','/procurement/orders'),['orders','Orders','items','Items']);
    const finalOrder=finalOrders.find(o=>String(idOf(o))===String(orderId));
    if(!finalNeed||!finalOrder) throw new Error('Read-after-write verification failed for material need/order.');
    step('verify-read-after-write',{ok:true,needVisible:true,orderVisible:true,needStatus:finalNeed.Status||null,orderStatus:finalOrder.Status||null});
    report.status='success';
  } catch (error) {
    report.status='failed';
    report.error=String(error && error.message || error).slice(0,1800);
  } finally {
    report.finishedAt=new Date().toISOString();
    fs.writeFileSync(path.join('test-results','staging-e2e-report.json'),JSON.stringify(report,null,2)+'\n');
    fs.writeFileSync(path.join('test-results','staging-e2e-report.md'),'# PMS Staging E2E\n\n- Status: **'+report.status+'**\n- Started: '+report.startedAt+'\n- Finished: '+report.finishedAt+'\n\n'+(report.error?'## Error\n\n'+report.error+'\n\n':'')+'## Steps\n\n'+report.steps.map(s=>'- '+s.name+': '+(s.ok?'PASS':'FAIL')+' — '+JSON.stringify(s)).join('\n')+'\n\n## Created test data\n\n'+JSON.stringify(report.created,null,2)+'\n');
    if(browser) await browser.close();
    console.log(JSON.stringify({status:report.status,steps:report.steps.map(s=>({name:s.name,ok:s.ok})),error:report.error||null},null,2));
    if(report.status!=='success') process.exitCode=1;
  }
})();
